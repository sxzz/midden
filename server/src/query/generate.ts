// Writes the query parser from its grammar with Peggy, a development
// dependency only: the server runs the committed `parser.generated.ts`, so
// nothing is generated at run time. `generate.test.ts` checks that the
// committed parser is what the grammar gives.
//
//   pnpm --filter @midden/server gen:query
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import peggy from 'peggy'

export const GRAMMAR = fileURLToPath(new URL('grammar.peggy', import.meta.url))
export const GENERATED = fileURLToPath(
  new URL('parser.generated.ts', import.meta.url),
)

/** The parser module the grammar gives, as it is committed. */
export function generateParser(grammar = readFileSync(GRAMMAR, 'utf8')) {
  const source = peggy.generate(grammar, {
    output: 'source',
    format: 'es',
    grammarSource: 'grammar.peggy',
  })
  return [
    `// Generated by Peggy ${peggy.VERSION} from grammar.peggy; do not edit.`,
    '// Run `pnpm --filter @midden/server gen:query` after changing the grammar.',
    '// @ts-nocheck',
    source,
  ].join('\n')
}

if (import.meta.main) {
  writeFileSync(GENERATED, generateParser())
  console.info(`wrote ${GENERATED}`)
}
